-- Requires verified backup, a planned maintenance window, and independent SQL review.
-- Intentionally no IF NOT EXISTS: conflicting pre-existing objects stop the migration.
-- Deliberately no customer PII, bank data, automatic messages or stock changes.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE repair_cases (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_reference varchar(64) NOT NULL UNIQUE,
  intake_key varchar(64) NOT NULL UNIQUE,
  location_id integer NOT NULL REFERENCES locations(id) ON DELETE RESTRICT,
  device_model varchar(100) NOT NULL,
  issue_category varchar(32) NOT NULL,
  status varchar(32) NOT NULL DEFAULT 'received',
  technician_id integer REFERENCES users(id) ON DELETE SET NULL,
  quote_amount numeric(12,2),
  approval_reference_digest varchar(64),
  quote_approved boolean NOT NULL DEFAULT false,
  approved_by_user_id integer REFERENCES users(id) ON DELETE SET NULL,
  parts_available boolean,
  qa_passed boolean NOT NULL DEFAULT false,
  revision integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_repair_status CHECK (
    status IN ('received','diagnosing','awaiting_approval','approved',
      'awaiting_parts','repairing','quality_check','ready','delivered','cancelled')),
  CONSTRAINT chk_repair_issue CHECK (
    issue_category IN ('screen','battery','charging','software','camera',
      'water_damage','micro_soldering','other')),
  CONSTRAINT chk_repair_quote CHECK (
    quote_amount IS NULL OR (quote_amount>0 AND quote_amount<=1000000)),
  CONSTRAINT chk_repair_revision CHECK (revision>=0),
  CONSTRAINT chk_repair_approved CHECK (
    quote_approved=false OR
      (quote_amount IS NOT NULL AND approval_reference_digest IS NOT NULL)),
  CONSTRAINT chk_repair_ready_qa CHECK (
    status NOT IN ('ready','delivered') OR qa_passed=true)
);
CREATE INDEX idx_repair_cases_location_status ON repair_cases(location_id,status);
CREATE INDEX idx_repair_cases_issue_category ON repair_cases(issue_category);
CREATE INDEX idx_repair_cases_technician_id ON repair_cases(technician_id);

CREATE TABLE repair_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id integer NOT NULL REFERENCES repair_cases(id) ON DELETE RESTRICT,
  event_key varchar(64) NOT NULL UNIQUE,
  event_type varchar(32) NOT NULL DEFAULT 'status_change',
  actor_user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  prior_status varchar(32) NOT NULL,
  next_status varchar(32) NOT NULL,
  revision integer NOT NULL,
  at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_repair_event_revision UNIQUE(case_id,revision),
  CONSTRAINT chk_repair_event_revision CHECK(revision>0),
  CONSTRAINT chk_repair_event_type CHECK(event_type IN ('status_change','assignment'))
);
CREATE INDEX idx_repair_events_case_id ON repair_events(case_id);
-- Application's default off-switch must remain off until DB and staff permissions are verified.
COMMIT;
